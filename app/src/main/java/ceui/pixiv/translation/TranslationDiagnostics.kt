package ceui.pixiv.translation

internal data class TranslationSessionDiagnostics(
    val conversationId: String,
    val promptVersion: Int,
    val promptConfigSource: String,
    val topLevelChunkMaxChars: Int,
    val parallelChunkCap: Int,
    val globalRequestCap: Int,
    val chunkAttemptCap: Int,
    val maxSplitDepth: Int,
    val priorityProcessing: Boolean,
)

internal data class TranslationResponseDiagnostics(
    val httpStatus: Int?,
    val contentType: String?,
    val requestId: String?,
    val completionId: String?,
    val responseModel: String?,
    val systemFingerprint: String?,
    val finishReason: String?,
    val promptTokens: Int?,
    val completionTokens: Int?,
    val totalTokens: Int?,
    val cachedPromptTokens: Int?,
    val reasoningTokens: Int?,
    val sseDataEvents: Int?,
    val malformedSseEvents: Int?,
    val apiErrorBody: String? = null,
)

internal data class TranslationAttemptRecord(
    val sequence: Long = 0,
    val topLevelChunkIndex: Int,
    val totalTopLevelChunks: Int,
    val splitPath: String,
    val splitDepth: Int,
    val attempt: Int,
    val maxAttempts: Int,
    val startedAtUtc: String,
    val durationMs: Long,
    val sourceText: String,
    val contextBeforeLength: Int,
    val contextAfterLength: Int,
    val promptMode: String,
    val systemPrompt: String,
    val userPrompt: String,
    val model: String,
    val reasoningEffort: String?,
    val temperature: Double,
    val priorityProcessing: Boolean,
    val response: TranslationResponseDiagnostics?,
    val rawModelOutput: String?,
    val normalizedModelOutput: String?,
    val validationClassification: String?,
    val sourceEqualsNormalizedOutput: Boolean?,
    val errorType: String?,
    val errorMessage: String?,
)

internal data class TranslationRetryDecisionRecord(
    val sequence: Long = 0,
    val topLevelChunkIndex: Int,
    val splitPath: String,
    val splitDepth: Int,
    val completedAttempt: Int,
    val classifiedError: String,
    val consecutiveRefusals: Int,
    val action: String,
    val shouldRetry: Boolean,
    val splitRequested: Boolean,
    val splitPerformed: Boolean,
    val currentChunkLength: Int,
    val requestedMaxChunkSize: Int?,
    val nextAlternativePrompt: Boolean?,
    val nextTemperature: Double?,
    val baseDelayMs: Long?,
    val terminalReason: String?,
)
